export const TOTAL_CII_ITEMS = SHEETS_CII.reduce((s, sh) => s + sh.items.length, 0)
export const TOTAL_CII_SUBITEMS = SHEETS_CII.reduce(
  (s, sh) => s + sh.items.reduce((ss, it) => ss + it.subItems.length, 0),
  0
)

export function calcItemAvg(itemId: number, scores: CIIScores): number | null {
  const sheet = SHEETS_CII.find((sh) => sh.items.some((it) => it.id === itemId))
  if (!sheet) return null
  const item = sheet.items.find((it) => it.id === itemId)
  if (!item) return null
  const scored = item.subItems.map((si) => scores[si.id]).filter((v): v is 1 | 2 | 3 => v !== undefined)
  if (scored.length === 0) return null
  return scored.reduce((a, b) => a + b, 0) / scored.length
}

export function calcSheetAvg(sheetId: 'D1' | 'D2' | 'D3', scores: CIIScores): number | null {
  const sheet = SHEETS_CII.find((sh) => sh.id === sheetId)
  if (!sheet) return null
  const avgs = sheet.items.map((it) => calcItemAvg(it.id, scores)).filter((v): v is number => v !== null)
  if (avgs.length === 0) return null
  return avgs.reduce((a, b) => a + b, 0) / avgs.length
}

export function calcOverallAvg(scores: CIIScores): number | null {
  const avgs = SHEETS_CII.map((sh) => calcSheetAvg(sh.id, scores)).filter((v): v is number => v !== null)
  if (avgs.length === 0) return null
  return avgs.reduce((a, b) => a + b, 0) / avgs.length
}

export function countScored(scores: CIIScores): number {
  return Object.keys(scores).length
}
